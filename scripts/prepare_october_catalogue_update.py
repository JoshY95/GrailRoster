"""Generate an atomic, repeatable catalogue-only update with preservation guards."""
import json
from collections import OrderedDict
from pathlib import Path

from add_2026_stadium_club_wwe import tables, slug

ROOT = Path(__file__).resolve().parents[1]
NOW = '2026-topps-now-wwe'


def now_rows():
    data = json.loads((ROOT / f'data/sets/{NOW}.json').read_text())['cards']
    sources = {r['number']: r for r in json.loads((ROOT / 'sources/topps-now-2025-2026/releases.json').read_text())['annualCards'] if r['year'] == 2026}
    result = OrderedDict(catalogue_cards=[], catalogue_variants=[])
    selected = [c for c in data if c['subsetCode'] == 'BASE' and 107 <= int(c['number']) <= 112]
    if len(selected) != 6:
        raise ValueError('Expected exactly NOW 107-112')
    for c in selected:
        s = sources[c['number']]
        result['catalogue_cards'].append(dict(id=c['id'], set_id=NOW, checklist_order=c['order'],
            category=c['category'], subset_code=c['subsetCode'], card_number=c['number'], display_name=c['name'],
            subject_1=c['name'].split(' / ')[0], subject_2=c['subject2'], roster=None, rookie=False,
            parallel_group='BASE', image_status='Missing', pricing_status='Unpriced', source_url=s['source'],
            notes=f"Official Topps listing; available {s['releaseDate']}; base print run {s['printRun']}. {s['publishedEditions']} Conditional Chrome tiers not met. Autograph extras remain notes without a separate verified checklist identifier."))
        result['catalogue_variants'].append(dict(id=c['id'] + '-IDENTITY', set_id=NOW, card_id=c['id'],
            variant_order=c['order'], subset='Regular', card_number=c['number'], display_name=c['name'],
            parallel='Checklist identity', serial_cap=None, serial_exact=None, exclusive_note=None,
            numbering_note='Unnumbered checklist identity; base print run is not a serial cap.',
            verification_status='Official Topps product listing'))
    for c in selected:
        for parallel, cap in [('Gold Foil', 50), ('Orange Foil', 25), ('Black Foil', 10), ('Red Foil', 5), ('FoilFractor', 1)]:
            result['catalogue_variants'].append(dict(id=c['id'] + '-' + slug(parallel), set_id=NOW, card_id=c['id'],
                variant_order=133 + len(result['catalogue_variants']) - 6, subset='Regular', card_number=c['number'],
                display_name=c['name'], parallel=parallel, serial_cap=cap,
                serial_exact='1/1' if cap == 1 else f'/{cap}', exclusive_note=None,
                numbering_note='Card-specific Topps product listing explicitly names this foil and serial cap.',
                verification_status='Official Topps product listing'))
    return result


def insert_guarded(table, rows):
    columns = list(rows[0])
    payload = json.dumps(rows, ensure_ascii=False, separators=(',', ':')).replace("'", "''")
    relation = f"jsonb_populate_recordset(null::public.{table},'{payload}'::jsonb)"
    key = 't.set_id=e.set_id and t.subset_code=e.subset_code' if table == 'catalogue_subsets' else 't.id=e.id'
    comparison = ' or '.join(f't.{c} is distinct from e.{c}' for c in columns)
    return f"""do $$ begin
 if exists(select 1 from public.{table} t join {relation} e on {key} where {comparison})
 then raise exception 'Conflicting {table} row; refusing overwrite'; end if;
end $$;
insert into public.{table}({','.join(columns)}) select {','.join(columns)} from {relation} on conflict do nothing;
"""


