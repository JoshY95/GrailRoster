#!/usr/bin/env python3
"""Generate an atomic additive import; old catalogue and collector rows are immutable."""
import json
from pathlib import Path
from add_2026_topps_chrome_star_wars import tables, SET_ID

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'supabase/corrections/2026-10-25-chrome-star-wars.sql'


def generate(data=None, *, set_id=SET_ID, baseline_sets=24, baseline_cards=11298):
    data = tables() if data is None else data
    added_cards = len(data['catalogue_cards'])
    final_sets, final_cards = baseline_sets+1, baseline_cards+added_cards
    watched = [*data, 'collection_items', 'reference_images']
    sql = ['-- Generated by scripts/prepare_star_wars_chrome_import.py; additive data only.',
           'begin;', "set local lock_timeout='5s';",
           'lock table '+','.join('public.'+t for t in data)+' in share row exclusive mode;']
    for table in watched:
        sql.append(f'create temporary table before_{table} on commit drop as select to_jsonb(t) as row from public.{table} t;')
    sql.append(f"""do $$ begin
 if (select count(*) from public.catalogue_sets) not in ({baseline_sets},{final_sets})
 or (select count(*) from public.catalogue_cards) not in ({baseline_cards},{final_cards})
 or ((select count(*) from public.catalogue_sets)={final_sets} and not exists(select 1 from public.catalogue_sets where id='{set_id}'))
 then raise exception 'Catalogue baseline changed; review import'; end if;
end $$;""")
    for table, rows in data.items():
        columns = list(rows[0])
        payload = json.dumps(rows,ensure_ascii=False,separators=(',',':')).replace("'","''")
        desired = 'desired_'+table
        sql.append(f"create temporary table {desired} on commit drop as select * from jsonb_populate_recordset(null::public.{table},'{payload}'::jsonb);")
        key = 't.set_id=e.set_id and t.subset_code=e.subset_code' if table == 'catalogue_subsets' else 't.id=e.id'
        comparison = ' or '.join(f't.{c} is distinct from e.{c}' for c in columns)
        sql.append(f"""do $$ begin
 if exists(select 1 from public.{table} t join {desired} e on {key} where {comparison})
 then raise exception 'Conflicting {table} identity; refusing overwrite'; end if;
end $$;
insert into public.{table}({','.join(columns)}) select {','.join(columns)} from {desired} on conflict do nothing;""")
    conditions = []
    for table, rows in data.items():
        key = 'id' if table == 'catalogue_sets' else 'set_id'
        conditions.append(f"(select count(*) from public.{table} where {key}='{set_id}')<>{len(rows)}")
    conditions.extend([
        f'(select count(*) from public.catalogue_sets)<>{final_sets}',
        f'(select count(*) from public.catalogue_cards)<>{final_cards}',
        f"exists(select 1 from public.catalogue_variants v left join public.catalogue_cards c on c.id=v.card_id where v.set_id='{set_id}' and (c.id is null or c.set_id<>v.set_id))",
        f"exists(select 1 from public.catalogue_subsets s where s.set_id='{set_id}' and s.card_count<>(select count(*) from public.catalogue_cards c where c.set_id=s.set_id and c.subset_code=s.subset_code))",
    ])
    for table in watched:
        conditions.append(f'exists(select row from before_{table} except all select to_jsonb(t) from public.{table} t)')
    for table in ('collection_items','reference_images'):
        conditions.append(f'exists(select to_jsonb(t) from public.{table} t except all select row from before_{table})')
    sql.append('do $$ begin\n if '+'\n or '.join(conditions)+"\n then raise exception 'Count, linkage or preservation check failed'; end if;\nend $$;")
    sql.append("select 'verified' as result,(select count(*) from public.catalogue_cards) as cards,(select count(*) from public.collection_items) as collections;")
    sql.append('commit;')
    return '\n'.join(sql)+'\n'


if __name__ == '__main__':
    OUT.write_text(generate())
    print(f'Generated guarded additive transaction: {OUT.name} ({OUT.stat().st_size} bytes)')
