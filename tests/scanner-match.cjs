const assert = require('node:assert/strict');
const {loadCatalogue} = require('../scripts/catalogue_io');
const M = require('../scanner-match');
const catalogue = loadCatalogue();
const before = JSON.stringify(catalogue);
const index = M.buildIndex(catalogue);
const target = catalogue.cards.find(c => c.setId === '2026-topps-stadium-club-wwe' && c.subsetCode === 'BASE' && c.number === '1');
assert.equal(target.name, 'Seth Rollins');
let matches = M.match(index, 'SETH ROLLINS\n2026 TOPPS STADIUM CLUB WWE\nBASE CARDS\n#1');
assert(matches.some(m => m.card.id === target.id));
assert.equal(matches[0].set.id, target.setId);
assert(matches[0].evidence.includes('Card number found'));
assert(matches[0].evidence.includes('Name found'));
assert.equal(M.match(index, 'SETH ROLLINS\n#1', target.setId)[0].set.id, target.setId);
assert(M.match(index, 'SETH ROLLINS').length > 1, 'Name alone must leave ambiguity');
assert(M.match(index, 'SETH ROLIINS\n#1', target.setId).some(m => m.card.id === target.id), 'One OCR character error tolerated');
assert.equal(M.match(index, 'SETH has many wrestling victories', target.setId).length, 0, 'One first name must not match a multi-word name');
assert.equal(M.match(index, '').length, 0);
assert.equal(M.match(index, 'PIKACHU 2025 #1').length, 0);
assert.equal(M.match(index, '#1').length, 0, 'No global match on number alone');
assert(M.match(index, '#1', target.setId).length > 0, 'A known set plus exact number may give candidates');
assert.equal(M.details('07/50\n2025\n#001').serial, '07/50');
assert(!M.details('07/50\n2025').explicit.has('50'));
assert(!M.details('07/50\n2025').possible.has('2025'));
assert.equal(M.normalize('“Ángel” & ÉLITE'), 'angel elite');
assert(M.details('No. AA-12').explicit.has('aa12'));
assert(M.match(index, 'John Cena').every(m => m.set.categoryId === 'wwe'));
assert.deepEqual(M.loadStore('broken', '2026-10'), {version:1,usage:{month:'2026-10',used:0},attempts:[],items:[]});
assert.equal(M.loadStore(JSON.stringify({version:1,usage:{month:'2026-10',used:8}}),'2026-10').usage.used,8);
assert.equal(M.loadStore(JSON.stringify({version:1,usage:{month:'2026-09',used:25}}),'2026-10').usage.used,0);
assert.equal(M.loadStore(JSON.stringify({version:1,usage:{month:'2026-10',used:999}}),'2026-10').usage.used,25);
assert.equal(JSON.stringify(catalogue),before,'Matching must not mutate any catalogue record');
console.log('Scanner catalogue matching, OCR ambiguity, serial isolation, monthly allowance and catalogue preservation passed.');
